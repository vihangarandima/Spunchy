// Writes supabase/seed.sql from src/content/products.js so the database and
// the demo data always start from the same list. `npm run seed-sql`
import { writeFile } from 'node:fs/promises';
import { SEED_PRODUCTS } from '../src/content/products.js';

const q = (v) => (v == null ? 'null' : typeof v === 'number' || typeof v === 'boolean' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const rows = SEED_PRODUCTS.map((p, i) =>
  `  (${[p.id, p.category, p.name_en, p.name_si, p.price, p.stock, p.is_available, p.image, i].map(q).join(', ')})`
);
const sql = `-- Generated by scripts/seed-sql.mjs. Prices from in-store labels (2026-11-08).
-- Stock values are samples: set real numbers from the staff page.
insert into public.products (id, category, name_en, name_si, price, stock, is_available, image, sort) values
${rows.join(',\n')}
on conflict (id) do nothing;
`;
await writeFile(new URL('../supabase/seed.sql', import.meta.url), sql);
console.log(`wrote ${SEED_PRODUCTS.length} products to supabase/seed.sql`);
